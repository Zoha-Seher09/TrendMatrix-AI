
"""
Database management for TrendMatrix AI.

Supports:
- PostgreSQL (Supabase) when DATABASE_URL is configured.
- SQLite for local development when DATABASE_URL is not configured.

The public function names and return formats are preserved.
"""

import json
import math
import os
import sqlite3

from contextlib import contextmanager
from datetime import datetime
from pathlib import Path
from typing import Optional

from config import DATABASE_PATH


DATABASE_URL = os.getenv("DATABASE_URL", "").strip()
USE_POSTGRES = bool(DATABASE_URL)


# --------------------------------------------------
# PostgreSQL connection adapter
# --------------------------------------------------

class PostgreSQLConnection:
    """Small adapter preserving the existing SQLite-style API."""

    def __init__(self, connection):
        self.connection = connection

    def execute(self, query, parameters=()):
        query = query.replace("?", "%s")
        return self.connection.execute(query, parameters)

    def executemany(self, query, parameters):
        query = query.replace("?", "%s")
        return self.connection.cursor().executemany(query, parameters)

    def commit(self):
        self.connection.commit()

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc_value, traceback):
        try:
            if exc_type is None:
                self.connection.commit()
            else:
                self.connection.rollback()
        finally:
            self.connection.close()

        return False


# --------------------------------------------------
# Database connection
# --------------------------------------------------

def get_connection():
    """Create a connection to PostgreSQL or local SQLite."""

    if USE_POSTGRES:
        try:
            import psycopg
            from psycopg.rows import dict_row

            connection = psycopg.connect(
                DATABASE_URL,
                connect_timeout=10,
                sslmode="require",
                row_factory=dict_row
            )

            return PostgreSQLConnection(connection)

        except Exception as error:
            raise RuntimeError(
                f"PostgreSQL connection failed: {error}"
            ) from error

    database_file = Path(DATABASE_PATH)
    database_file.parent.mkdir(parents=True, exist_ok=True)

    connection = sqlite3.connect(
        str(database_file),
        timeout=30
    )

    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")
    connection.execute("PRAGMA journal_mode = WAL")

    return connection


@contextmanager
def database_connection():
    """Provide a connection and ensure it is closed."""

    connection = get_connection()

    try:
        with connection:
            yield connection
    finally:
        if isinstance(connection, sqlite3.Connection):
            connection.close()


