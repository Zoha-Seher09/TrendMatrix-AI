def init_db() -> None:
    """Create required tables and indexes if they do not exist."""

    if USE_POSTGRES:
        statements = [
            """
            CREATE TABLE IF NOT EXISTS datasets (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                variable_name TEXT NOT NULL,
                variable_code TEXT,
                description TEXT,
                unit TEXT,
                data_source TEXT NOT NULL,
                region_name TEXT NOT NULL,
                latitude DOUBLE PRECISION,
                longitude DOUBLE PRECISION,
                start_date TEXT NOT NULL,
                end_date TEXT NOT NULL,
                frequency TEXT NOT NULL,
                data_type TEXT NOT NULL DEFAULT 'NASA',
                is_sample INTEGER NOT NULL DEFAULT 0,
                metadata_json TEXT,
                fetched_at TEXT NOT NULL,
                created_at TEXT NOT NULL
            )
            """,
            """
            CREATE TABLE IF NOT EXISTS observations (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                dataset_id BIGINT NOT NULL REFERENCES datasets(id)
                    ON DELETE CASCADE,
                observation_date TEXT NOT NULL,
                value DOUBLE PRECISION NOT NULL,
                quality_flag TEXT,
                UNIQUE(dataset_id, observation_date)
            )
            """,
            """
            CREATE INDEX IF NOT EXISTS idx_dataset_variable
            ON datasets(variable_name)
            """,
            """
            CREATE INDEX IF NOT EXISTS idx_dataset_region
            ON datasets(region_name)
            """,
            """
            CREATE INDEX IF NOT EXISTS idx_observation_date
            ON observations(observation_date)
            """,
            """
            CREATE INDEX IF NOT EXISTS idx_observation_dataset
            ON observations(dataset_id)
            """
        ]

        with database_connection() as connection:
            for statement in statements:
                connection.execute(statement)

        return

    # Existing SQLite initialization.
    with database_connection() as connection:
        connection.execute("""
            CREATE TABLE IF NOT EXISTS datasets (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                variable_name TEXT NOT NULL,
                variable_code TEXT,
                description TEXT,
                unit TEXT,
                data_source TEXT NOT NULL,
                region_name TEXT NOT NULL,
                latitude REAL,
                longitude REAL,
                start_date TEXT NOT NULL,
                end_date TEXT NOT NULL,
                frequency TEXT NOT NULL,
                data_type TEXT NOT NULL DEFAULT 'NASA',
                is_sample INTEGER NOT NULL DEFAULT 0,
                metadata_json TEXT,
                fetched_at TEXT NOT NULL,
                created_at TEXT NOT NULL
            )
        """)

        connection.execute("""
            CREATE TABLE IF NOT EXISTS observations (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                dataset_id INTEGER NOT NULL,
                observation_date TEXT NOT NULL,
                value REAL NOT NULL,
                quality_flag TEXT,
                FOREIGN KEY (dataset_id)
                    REFERENCES datasets(id)
                    ON DELETE CASCADE,
                UNIQUE(dataset_id, observation_date)
            )
        """)

        connection.execute("""
            CREATE INDEX IF NOT EXISTS idx_dataset_variable
            ON datasets(variable_name)
        """)

        connection.execute("""
            CREATE INDEX IF NOT EXISTS idx_dataset_region
            ON datasets(region_name)
        """)

        connection.execute("""
            CREATE INDEX IF NOT EXISTS idx_observation_date
            ON observations(observation_date)
        """)

        connection.execute("""
            CREATE INDEX IF NOT EXISTS idx_observation_dataset
            ON observations(dataset_id)
        """)


