def save_dataset(dataset: dict) -> int:
    """Save dataset metadata and return its database ID."""

    required_fields = [
        "variable_name",
        "data_source",
        "region_name",
        "start_date",
        "end_date",
        "frequency"
    ]

    for field in required_fields:
        if not dataset.get(field):
            raise ValueError(
                f"Missing required dataset field: {field}"
            )

    now = datetime.now().astimezone().isoformat()

    metadata_json = json.dumps(
        dataset.get("metadata", {}),
        ensure_ascii=False
    )

    query = """
        INSERT INTO datasets (
            variable_name,
            variable_code,
            description,
            unit,
            data_source,
            region_name,
            latitude,
            longitude,
            start_date,
            end_date,
            frequency,
            data_type,
            is_sample,
            metadata_json,
            fetched_at,
            created_at
        )
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    """

    parameters = (
        dataset["variable_name"],
        dataset.get("variable_code"),
        dataset.get("description"),
        dataset.get("unit"),
        dataset["data_source"],
        dataset["region_name"],
        dataset.get("latitude"),
        dataset.get("longitude"),
        dataset["start_date"],
        dataset["end_date"],
        dataset["frequency"],
        dataset.get("data_type", "NASA"),
        int(dataset.get("is_sample", False)),
        metadata_json,
        now,
        now
    )

    with database_connection() as connection:

        if USE_POSTGRES:
            row = connection.execute(
                query + " RETURNING id",
                parameters
            ).fetchone()

            return row["id"]

        cursor = connection.execute(query, parameters)
        return cursor.lastrowid


# --------------------------------------------------
# Observation management
# --------------------------------------------------

def save_observations(
    dataset_id: int,
    observations: list[dict]
) -> int:
    """Save observations, updating existing dataset/date records."""

    if not observations:
        return 0

    prepared_records = []

    for observation in observations:
        observation_date = observation.get("date")
        value = observation.get("value")

        if not observation_date or value is None:
            raise ValueError(
                "Every observation requires a date and value."
            )

        try:
            datetime.fromisoformat(str(observation_date))
        except ValueError as error:
            raise ValueError(
                f"Invalid observation date: {observation_date}"
            ) from error

        numeric_value = float(value)

        if not math.isfinite(numeric_value):
            raise ValueError(
                "Observation values must be finite numbers."
            )

        prepared_records.append((
            dataset_id,
            str(observation_date),
            numeric_value,
            observation.get("quality_flag")
        ))

    with database_connection() as connection:

        dataset_exists = connection.execute(
            "SELECT id FROM datasets WHERE id = ?",
            (dataset_id,)
        ).fetchone()

        if dataset_exists is None:
            raise ValueError(
                f"Dataset with ID {dataset_id} does not exist."
            )

        connection.executemany("""
            INSERT INTO observations (
                dataset_id,
                observation_date,
                value,
                quality_flag
            )
            VALUES (?, ?, ?, ?)
            ON CONFLICT(dataset_id, observation_date)
            DO UPDATE SET
                value = excluded.value,
                quality_flag = excluded.quality_flag
        """, prepared_records)

    return len(prepared_records)


# --------------------------------------------------
# Dataset retrieval
# --------------------------------------------------

def get_dataset(dataset_id: int) -> Optional[dict]:
    """Retrieve one dataset by ID."""

    with database_connection() as connection:
        row = connection.execute("""
            SELECT *
            FROM datasets
            WHERE id = ?
        """, (dataset_id,)).fetchone()

        return dict(row) if row else None


def list_datasets(
    variable_name: Optional[str] = None,
    region_name: Optional[str] = None
) -> list[dict]:
    """Return available datasets with optional filters."""

    query = "SELECT * FROM datasets WHERE 1 = 1"
    parameters = []

    if variable_name:
        query += " AND variable_name = ?"
        parameters.append(variable_name)

    if region_name:
        query += " AND region_name = ?"
        parameters.append(region_name)

    query += " ORDER BY fetched_at DESC"

    with database_connection() as connection:
        rows = connection.execute(
            query,
            parameters
        ).fetchall()

        return [dict(row) for row in rows]


# --------------------------------------------------
# Offline observation retrieval
# --------------------------------------------------

def get_observations(dataset_id: int) -> list[dict]:
    """Retrieve cached observations in chronological order."""

    with database_connection() as connection:
        rows = connection.execute("""
            SELECT
                observation_date,
                value,
                quality_flag
            FROM observations
            WHERE dataset_id = ?
            ORDER BY observation_date ASC
        """, (dataset_id,)).fetchall()

        return [dict(row) for row in rows]


# --------------------------------------------------
# Database statistics
# --------------------------------------------------

def get_database_stats() -> dict:
    """Return database storage statistics."""

    with database_connection() as connection:

        dataset_count = connection.execute(
            "SELECT COUNT(*) AS total FROM datasets"
        ).fetchone()

        observation_count = connection.execute(
            "SELECT COUNT(*) AS total FROM observations"
        ).fetchone()

        cached_count = connection.execute("""
            SELECT COUNT(*) AS total
            FROM datasets
            WHERE is_sample = 0
        """).fetchone()

        sample_count = connection.execute("""
            SELECT COUNT(*) AS total
            FROM datasets
            WHERE is_sample = 1
        """).fetchone()

        if USE_POSTGRES:
            return {
                "total_datasets": dataset_count["total"],
                "total_observations": observation_count["total"],
                "cached_nasa_datasets": cached_count["total"],
                "sample_datasets": sample_count["total"]
            }

        return {
            "total_datasets": dataset_count["total"],
            "total_observations": observation_count["total"],
            "cached_nasa_datasets": cached_count["total"],
            "sample_datasets": sample_count["total"]
        }


